    }

    fun getLocalizedDayName(dayOfWeek: Int, lang: String): String {
        val isEn = lang.equals("en", ignoreCase = true)
        return when (dayOfWeek) {
            Calendar.SUNDAY -> if (isEn) "Sunday" else "الأحد"
            Calendar.MONDAY -> if (isEn) "Monday" else "الإثنين"
            Calendar.TUESDAY -> if (isEn) "Tuesday" else "الثلاثاء"
            Calendar.WEDNESDAY -> if (isEn) "Wednesday" else "الأربعاء"
            Calendar.THURSDAY -> if (isEn) "Thursday" else "الخميس"
            Calendar.FRIDAY -> if (isEn) "Friday" else "الجمعة"
            Calendar.SATURDAY -> if (isEn) "Saturday" else "السبت"
            else -> if (isEn) "Today" else "اليوم"
        }
    }
